function gradeQuiz() {
    let questions = lessons[currentLesson].questions;
    let score = 0;
    let unanswered = 0;
    let details = "";

    questions.forEach((q, i) => {
        let selected = document.querySelector(
            `input[name="q${i}"]:checked`
        );

        if (!selected) {
            unanswered++;
            details += `<p>السؤال ${i + 1}: لم تتم الإجابة عنه.</p>`;
            return;
        }

        let answer = Number(selected.value);

        if (answer === q[2]) {
            score++;
            details += `<p class="correct">السؤال ${i + 1}: إجابة صحيحة ✓</p>`;
        } else {
            details += `
                <p class="incorrect">
                    السؤال ${i + 1}: إجابة غير صحيحة ✗
                    <br>الإجابة الصحيحة: ${q[1][q[2]]}
                </p>
            `;
        }
    });

    if (unanswered > 0) {
        document.getElementById("quizResult").innerHTML =
            `<p>أجيبي عن جميع الأسئلة أولًا. الأسئلة المتبقية: ${unanswered}</p>`;
        return;
    }

    let results = getData("quizResults", {});

    let previous = results[currentLesson];

    // الاحتفاظ بأفضل درجة حصل عليها الطالب
    if (!previous || score > previous.score) {
        results[currentLesson] = {
            score: score,
            date: new Date().toLocaleDateString("ar-EG")
        };
    }

    localStorage.setItem("quizResults", JSON.stringify(results));

    let completed = getData("completedLessons", []);

    if (!completed.includes(currentLesson)) {
        completed.push(currentLesson);
    }

    localStorage.setItem(
        "completedLessons",
        JSON.stringify(completed)
    );

    let message = score >= 8
        ? "ممتاز! أداء رائع."
        : score >= 5
        ? "جيد جدًا، راجعي بعض أجزاء الدرس."
        : "حاولي مراجعة الدرس مرة أخرى.";

    document.getElementById("quizForm").innerHTML = "";

    document.getElementById("quizResult").innerHTML = `
        <div class="result-box">
            <h2>نتيجة الاختبار</h2>
            <h1>${score} / 10</h1>
            <p>${message}</p>
            <p>تم تسجيل إتمام الدرس.</p>
        </div>

        <h3>مراجعة الإجابات</h3>
        ${details}

        <button class="primary" onclick="openLesson(${currentLesson})">
            مراجعة الدرس
        </button>

        <button class="secondary" onclick="showPage('home')">
            العودة للرئيسية
        </button>
    `;

    updateDashboard();
}

// تحديث لوحة التقدم

function updateDashboard() {
    let completed = getData("completedLessons", []);
    let student = getData("studentInfo", null);

    let percent = Math.round(
        completed.length / lessons.length * 100
    );

    document.getElementById("progressText").textContent =
        `أتممت ${completed.length} من 3 دروس`;

    document.getElementById("progressFill").style.width =
        percent + "%";

    document.getElementById("progressPercent").textContent =
        percent + "% إنجاز";

    let names = completed.map(i => lessons[i].title);

    document.getElementById("completedNames").textContent =
        names.length
        ? "الدروس المكتملة: " + names.join(" - ")
        : "لم يتم إكمال أي درس بعد.";

    lessons.forEach((lesson, i) => {
        let status = document.getElementById("status" + i);

        if (completed.includes(i)) {
            status.textContent = "✓ تم إكمال الدرس";
            status.classList.add("done");
        } else {
            status.textContent = "لم يتم إكمال الدرس";
            status.classList.remove("done");
        }
    });

    if (student) {
        document.getElementById("welcomeName").textContent =
            "أهلًا بك يا " + student.name;
    }
}

// عرض بيانات الطالب المحفوظة

function loadStudent() {
    let student = getData("studentInfo", null);

    if (student) {
        document.getElementById("studentName").value = student.name;
        document.getElementById("studentGrade").value = student.grade;
    }

    updateDashboard();
}

// الشهادة

function showCertificate() {
    let student = getData("studentInfo", null);
    let completed = getData("completedLessons", []);

    let area = document.getElementById("certificateArea");

    if (!student) {
        area.innerHTML = `
            <p>يرجى تسجيل بيانات الطالب أولًا.</p>
            <button class="primary" onclick="showPage('student')">
                تسجيل البيانات
            </button>
        `;
        return;
    }

    if (completed.length !== 3) {
        area.innerHTML = `
            <p>لم تكملي الدروس الثلاثة بعد.</p>
            <p>الدروس المكتملة: ${completed.length} من 3</p>
            <button class="primary" onclick="showPage('home')">
                العودة للدروس
            </button>
        `;
        return;
    }

    let results = getData("quizResults", {});

    let scores = lessons.map((lesson, i) =>
        results[i] ? results[i].score : 0
    );

    let total = scores.reduce((a, b) => a + b, 0);

    area.innerHTML = `
        <div class="certificate">
            <h1>شهادة إتمام رحلة التعلم</h1>
            <h2>تشهد البيئة التعليمية التفاعلية</h2>
            <p>بأن الطالب / الطالبة</p>
            <div class="student">${student.name}</div>
            <p>من ${student.grade}</p>
            <p>قد أتم الدروس التعليمية الثلاثة في مادة البرمجة والذكاء الاصطناعي.</p>
            <h2>مجموع أفضل الدرجات: ${total} / 30</h2>
            <p>نتمنى لك دوام النجاح والتفوق.</p>
            <p>التاريخ: ${new Date().toLocaleDateString("ar-EG")}</p>
        </div>

        <button class="primary wide" onclick="window.print()">
            طباعة الشهادة
        </button>
    `;
}

